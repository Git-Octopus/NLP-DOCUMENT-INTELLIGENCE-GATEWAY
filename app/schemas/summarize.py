from pydantic import BaseModel, Field, ConfigDict
from typing import List, Optional


class SummarizeRequest(BaseModel):
    text: str = Field(
        ..., min_length=10, description="Text or document content to summarize"
    )
    max_length: Optional[int] = Field(
        150, ge=10, le=1000, description="Target word count for summary"
    )

    model_config = ConfigDict(
        json_schema_extra={
            "example": {
                "text": (
                    "Hello support team, I have been attempting to access my corporate account "
                    "for the last three days. Every time I input my password, the screen displays "
                    "Error 503 Service Unavailable. I have already cleared cache and cookies, "
                    "reset my network settings, and tried two different browsers without any success. "
                    "Please help me regain access as this is blocking critical work."
                ),
                "max_length": 50,
            }
        }
    )


class SummarizeResponse(BaseModel):
    summary: str = Field(
        ...,
        description="Concise text summary generated by the LLM / extraction pipeline",
    )
    key_points: List[str] = Field(
        default_factory=list, description="Extracted bullet points or key highlights"
    )
    original_word_count: int = Field(
        ..., ge=0, description="Word count of the input text"
    )
    summary_word_count: int = Field(
        ..., ge=0, description="Word count of the generated summary"
    )

    model_config = ConfigDict(
        json_schema_extra={
            "example": {
                "summary": (
                    "User unable to access corporate account for three days due to "
                    "persistent Error 503 across multiple browsers."
                ),
                "key_points": [
                    "Account access blocked by Error 503 for 3 days",
                    "Troubleshooting steps (cache clearing, browser change) failed",
                    "Urgent resolution required",
                ],
                "original_word_count": 62,
                "summary_word_count": 16,
            }
        }
    )
